export function findPackCase(packId: string, index: number): { pack: Pack; testCase: NewCase } | null {
  const pack = PACKS.find((p) => p.id === packId);
  const testCase = pack?.cases[index];
  return pack && testCase ? { pack, testCase } : null;
}
